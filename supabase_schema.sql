create extension if not exists "pgcrypto";

create table if not exists public.teams (
 id uuid primary key default gen_random_uuid(),
 team_name text not null,
 captain text not null,
 phone text not null,
 player1_uid text not null,
 player2_uid text not null,
 player3_uid text not null,
 player4_uid text not null,
 created_at timestamptz not null default now()
);

create table if not exists public.matches (
 id bigint generated by default as identity primary key,
 match_no int unique not null,
 time text,
 room_id text,
 room_password text
);

create table if not exists public.settings (
 key text primary key,
 value text not null default ''
);

create table if not exists public.scores (
 id bigint generated by default as identity primary key,
 team_id uuid references public.teams(id) on delete cascade,
 placement_points int not null default 0,
 kill_points int not null default 0,
 created_at timestamptz not null default now()
);

create or replace view public.leaderboard as
select t.id as team_id,t.team_name,
coalesce(sum(s.placement_points+s.kill_points),0)::int as points
from teams t left join scores s on s.team_id=t.id
group by t.id,t.team_name;

alter table public.teams enable row level security;
alter table public.matches enable row level security;
alter table public.settings enable row level security;
alter table public.scores enable row level security;

create policy "public can register" on public.teams for insert to anon with check (true);
create policy "public can view teams count/details" on public.teams for select to anon using (true);
create policy "public can view matches" on public.matches for select to anon using (true);
create policy "public can view settings" on public.settings for select to anon using (true);
create policy "public can view leaderboard" on public.scores for select to anon using (true);

