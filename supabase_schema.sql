-- Change this password before launch.
create or replace function public.admin_login(p text) returns text
language plpgsql security definer as $$
begin
 if p = 'CHANGE_THIS_ADMIN_PASSWORD' then
   return encode(gen_random_bytes(24),'hex');
 end if;
 return null;
end; $$;
grant execute on function public.admin_login(text) to anon;
